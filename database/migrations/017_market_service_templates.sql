-- =============================================================
-- 3) راستی‌آزمایی
--
-- انتظار بعد از اجرا:
--   universal_rows  = ۱۲
--   brands_covered  = ۳۸
--   model_rows      = همهٔ ردیف‌های مدلیِ قبلی + تسمه تایم‌ها
--   total_rows      = حدود ۵۸۰
-- =============================================================

select
  count(*)                                               as total_rows,
  count(*) filter (where brand = '')                     as universal_rows,
  count(*) filter (where brand <> '' and model = '')     as brand_rows,
  count(*) filter (where brand <> '' and model <> '')    as model_rows,
  count(distinct brand) filter (where brand <> '')       as brands_covered,
  count(distinct brand || '/' || model)                  as distinct_pairs
from public.service_templates;


