-- =============================================================
-- 017 — پوشش کامل بازار خودروی ایران (service_templates)
-- =============================================================
--
-- مشکل:
--   با migration 016 فقط ۲۳ جفت (brand, model) برنامهٔ
--   نگهداری داشتند. هر خودرویی خارج از آن فهرست — مثلاً
--   «کیا / سلتوس» یا «هاوال / H6» — به برنامهٔ عمومیِ چهار
--   ردیفی برمی‌گشت و امتیاز سلامتش تقریباً همیشه «نامشخص»
--   می‌ماند.
--
-- منبع داده:
--   لیست خودروهای واقعاً در فروش از باما (bama.ir/price،
--   به تفکیک شرکت سازنده) و جدول‌های سرویس دوره‌ای سازنده‌ها:
--     * ایران خودرو — دفترچهٔ سرویس دوره‌ای (XU7/TU5/EF7/CF4)
--     * سایپا       — دفترچهٔ راهنما (dms.saipayadak.org)
--                     + جدول سرویس ساینا (persiankhodro.com)
--     * کیا         — ownersmanual.kia.com
--     * تویوتا      — Scheduled Maintenance Guide
--
-- راه‌حل: سه لایه
--   ۱) عمومی  (brand = '' , model = '')  → برای هر خودرو
--   ۲) برند   (brand <> '' , model = '') → هر مدلِ همان برند
--   ۳) مدل    (brand + model)           → فقط همان خودرو
--
--   موتور سلامت (filterTemplatesForVehicle) از پایین به بالا
--   fallback می‌زند؛ بنابراین «هر مدلی از هر برندِ جدول»
--   برنامهٔ نگهداری دارد، حتی اگر ردیف اختصاصی نداشته باشد.
--   لایهٔ ۲ کلید اصلی پوشش است: ۳۸ برند × ۱۲ سرویس.
--
-- دقت داده‌ها:
--   * برندها با «فاصلهٔ معمولی» نوشته شده‌اند نه نیم‌فاصله،
--     چون normalizeLabel نیم‌فاصلهٔ تایپ‌شده کاربر را به
--     فاصله تبدیل می‌کند ← هر دو شکل تطبیق پیدا می‌کنند.
--   * اینترکول‌ها عمداً کمی زودتر از کاتالوگ سازنده گذاشته
--     شده‌اند؛ تعویض زودتر ضرر ندارد، تأخیر ضرر دارد.
--   * «تسمه تایم» فقط برای مدل‌هایی آمده که موتورشان
--     واقعاً تسمه دارد (XU7، TU5، EF7، M13، M15). موتورهای
--     زنجیری عمداً ردیف ندارند: دادنِ عدد غلط بدتر از نبودن است.
--
-- بدون unique constraint روی (brand, model, service_name)،
-- پس مثل ۰۱۱ و ۰۱۶ با not exists درج می‌شود تا اجرای
-- چندباره ردیف تکراری نسازد. به‌همین‌دلیل ردیف‌هایی که از
-- قبل با مقدار دیگری ثبت شده‌اند حفظ می‌شوند و تغییر نمی‌کنند.
--
-- نکتهٔ موتور سلامت:
--   لایهٔ برند و لایهٔ مدل ممکن است یک سرویس را هر دو
--   داشته باشند (مثلاً «شمع» برای کیا و برای سراتو). موتور با
--   dedupePreferExactModel ردیفِ مدلِ دقیق را برنده می‌کند تا
--   سرویس در فرمِ ثبت دوبار نشان داده نشود و امتیاز سلامت هم
--   دو بار حساب نشود. (تغییر همراه: vehicleHealthEngine.js)
-- =============================================================


