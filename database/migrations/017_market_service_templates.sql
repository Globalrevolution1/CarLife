  brand,
  model,
  count(*) as services
from public.service_templates
where (brand, model) in (
  ('کیا', 'سلتوس'),
  ('هاوال', 'H6'),
  ('بی وای دی', 'سونگ'),
  ('تویوتا', 'پرادو'),
  ('مرسدس بنز', ''),
  ('چری', '')
)
group by brand, model
order by brand, model;
