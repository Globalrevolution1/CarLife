-- =============================================================
-- 016 — پوشش سرویس‌های دوره‌ای (service_templates)
-- =============================================================
--
-- مشکل:
--   فقط ۲ جفت (brand, model) در جدول دادهٔ مرجع داشتیم:
--     پژو   / 206 تیپ 2   (۷ ردیف)
--     لکسوس / ls460L       (۳ ردیف)
--   هر خودروی دیگری ثبت می‌شد ← هیچ سرویسی نمایش داده می‌شد
--   ← «برنامه نگهداری پیشنهادی» خالی و امتیاز سلامت نامشخص.
--
-- راه‌حل دو لایه:
--   ۱) دادهٔ «عمومی» با brand/model خالی → برای همهٔ خودروها
--      کار می‌کند. موتور سلامت (filterTemplatesForVehicle)
--      ردیف‌های عمومی را ردیف‌های خاص ترجیح می‌دهد.
--   ۲) ردیف‌های مدل‌محور برای پرتیراژترین خودروهای ایران،
--      فقط برای سرویس‌هایی که مقدارشان واقعاً به مدل بستگی دارد.
--
-- دقت داده‌ها:
--   * «تعویض روغن موتور ۱۰,۰۰۰» و «فیلتر روغن ۱۰,۰۰۰»
--     مقادیر مرجع پراکنده‌ترین خودروهای بنزینی سواری است.
--   * «روغن گیربکس ۵۰,۰۰۰» عمداً زودتر از برخی کاتالوگ‌ها
--     گذاشته شده؛ تعویض زودتر هیچ آسیبی ندارد.
--   * «تسمه تایم» عمداً اضافه نشده چون خیلی از موتورها
--     زنجیر دارند و دادن عدد غلط بدتر از نبودن است.
--
-- بدون unique constraint، پس مثل 011 با not exists درج می‌شود
-- تا اجرای چندباره ردیف تکراری نسازد.
--
-- جدول عمومی‌ها: brand = '' و model = '' یعنی «برای همه».
--   comment روی جدول هم به‌روز شده.
-- =============================================================


-- =============================================================
-- 1) توضیح جدول: قرارداد «عمومی» را ثبت می‌کنیم
-- =============================================================

comment on table public.service_templates is
  'جدول مرجع سرویس‌های دوره‌ای. مدل‌محور: هر ردیف یک جفت (brand, model). ردیف با brand خالی یعنی برای همهٔ خودروها.';


-- =============================================================
-- 2) دادهٔ مرجع — ردیف‌های عمومی
-- =============================================================

insert into public.service_templates
  (brand, model, service_name, interval_km)
select
  seed.brand,
  seed.model,
  seed.service_name,
  seed.interval_km
from (
  values
    ('', '', 'تعویض روغن موتور', 10000),
    ('', '', 'فیلتر روغن',       10000),
    ('', '', 'فیلتر هوا',        15000),
    ('', '', 'فیلتر کابین',      15000)
) as seed (brand, model, service_name, interval_km)
where not exists (
  select 1
    from public.service_templates existing
   where existing.brand        = seed.brand
     and existing.model        = seed.model
     and existing.service_name = seed.service_name
);


-- =============================================================
-- 3) ردیف‌های مدل‌محور برای خودروهای پرتیراژ
--
-- فقط دو سرویس که مقدارشان واقعاً به خودرو بستگی دارد:
--   روغن گیربکس / شمع
-- چهار سرویس پایه با ردیف عمومی بالا پوشش داده می‌شوند.
